// The console BFF mocked in the browser, with the rules `crates/http/src/console` enforces
// (tested there for real): the cookie finds the session, state changes carry the CSRF token,
// the admin proxy needs an AIS by the session's device Instance key, and the ADP proxy adds no
// credential, so a body without the browser's AIS reads as Anonymous (Public only).
import { readFile } from "node:fs/promises";

import type { BrowserContext, Route } from "@playwright/test";
import { loadKernel, type Kernel } from "@esuiss/access";

export const COOKIE = "__Host-access-console";
export const CSRF = "__Host-access-console-csrf";

/** Canonical intent envelopes generated by the Kernel (`sdks/bindings/wasm` tests). */
export const CREATE_ENVELOPE =
  "o2ZhY3Rpb26kZG5hbWVvaW5zdGFuY2VfY3JlYXRlZW1ham9yAWZzY2hlbWGCL1ggBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwcHBwdpbmFtZXNwYWNlZmFjY2Vzc2h2YWxpZGl0eYIZA-gZB9BpcmVzb3VyY2VzgaNkcGF0aIFkMDEwMWluYW1lc3BhY2VsYWNjZXNzLnBhcnR5a2luY2FybmF0aW9uAA";

const DOMAIN = Buffer.alloc(32, 3).toString("base64url");
const BASIS = Buffer.alloc(16, 1).toString("base64url");
const PARTY = Buffer.alloc(16, 2).toString("base64url");

let kernel: Promise<Kernel> | undefined;

function k(): Promise<Kernel> {
  kernel ??= readFile(
    new URL("../../../sdks/typescript/wasm/access_kernel_wasm_bg.wasm", import.meta.url),
  ).then((bytes) => loadKernel(bytes));
  return kernel;
}

/** The byte strings of a tagged `COSE_Sign1` (test-side reading only). */
function sign1Parts(bytes: Uint8Array): {
  protected: Uint8Array;
  payload: Uint8Array;
  sig: Uint8Array;
} {
  let at = 2;
  const bstr = (): Uint8Array => {
    const head = bytes[at] ?? 0;
    if (head === 0xa0) {
      at += 1;
      return new Uint8Array();
    }
    let len = head & 0x1f;
    at += 1;
    if (len === 24) {
      len = bytes[at] ?? 0;
      at += 1;
    } else if (len === 25) {
      len = ((bytes[at] ?? 0) << 8) | (bytes[at + 1] ?? 0);
      at += 2;
    }
    const out = bytes.slice(at, at + len);
    at += len;
    return out;
  };
  const p = bstr();
  bstr();
  const payload = bstr();
  const sig = bstr();
  return { protected: p, payload, sig };
}

interface Session {
  readonly account: string;
  csrf: string;
  key?: CryptoKey;
  kid?: string;
  ended: boolean;
}

export interface Seen {
  readonly method: string;
  readonly path: string;
  readonly ais: boolean;
  readonly status: number;
}

export class ConsoleMock {
  readonly sessions = new Map<string, Session>();
  readonly seen: Seen[] = [];
  /** What the eligibility check answers for a registered Instance's account. */
  eligible = new Set<string>();
  /** Make the session store fail (Ek B 2973). */
  down = false;

  /** A signed-in session, as the hosted login hand-off leaves it, in `context`. */
  async signIn(context: BrowserContext, baseURL: string, account = "acc_ada"): Promise<string> {
    const value = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64url");
    const csrf = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64url");
    this.sessions.set(value, { account, csrf, ended: false });
    await context.addCookies([
      {
        name: COOKIE,
        value,
        domain: new URL(baseURL).hostname,
        path: "/",
        httpOnly: true,
        secure: true,
        sameSite: "Strict",
      },
      {
        name: CSRF,
        value: csrf,
        domain: new URL(baseURL).hostname,
        path: "/",
        secure: true,
        sameSite: "Strict",
      },
    ]);
    return value;
  }

  async install(context: BrowserContext): Promise<void> {
    await context.route("**/console/api/**", (route) => this.handle(route));
  }

  private async verify(s: Session, ais: string | undefined, mode: string): Promise<boolean> {
    if (ais === undefined || s.key === undefined || s.kid === undefined) return false;
    const kernel = await k();
    const parts = sign1Parts(Buffer.from(ais, "base64url"));
    const tbs = Uint8Array.from(kernel.coseToBeSigned(parts.protected, parts.payload));
    const ok = await crypto.subtle.verify(
      { name: "ECDSA", hash: "SHA-256" },
      s.key,
      Uint8Array.from(parts.sig),
      tbs,
    );
    if (!ok) return false;
    const st = JSON.parse(kernel.describeStatement(parts.payload)) as { mode: string };
    return st.mode === mode;
  }

  private async handle(route: Route): Promise<void> {
    const r = route.request();
    const url = new URL(r.url());
    const path = url.pathname.replace("/console/api", "");
    const headers = await r.allHeaders();
    const cookies = new Map(
      (headers["cookie"] ?? "")
        .split(";")
        .map((c) => c.trim().split("=", 2))
        .filter((c): c is [string, string] => c.length === 2),
    );
    const reply = async (status: number, body?: unknown) => {
      this.seen.push({
        method: r.method(),
        path,
        ais: headers["x-access-ais"] !== undefined,
        status,
      });
      await route.fulfill({
        status,
        contentType: "application/json",
        body: body === undefined ? "" : JSON.stringify(body),
      });
    };
    const problem = (status: number, code: string, reason?: string) =>
      reply(status, { type: `urn:suiss:access:problem:${code}`, status, code, reason });

    if (this.down) return problem(503, "unavailable");
    const value = cookies.get(COOKIE);
    const s = value === undefined ? undefined : this.sessions.get(value);
    if (s === undefined || s.ended) return problem(401, "console-session-required");
    if (r.method() !== "GET" && headers["x-csrf-token"] !== s.csrf) {
      return problem(403, "csrf-token-invalid");
    }
    const body = (): Record<string, unknown> => (r.postDataJSON() ?? {}) as Record<string, unknown>;

    if (path === "/session") {
      return reply(200, {
        account: s.account,
        display_name: "<img src=x onerror=alert(1)>Ada",
        realm: "acme",
        domain: DOMAIN,
        expires_at: new Date(Date.now() + 12 * 3600_000).toISOString(),
        idle_timeout_s: "900",
        instance: s.kid ?? null,
      });
    }
    if (path === "/about") return reply(200, { server_version: "0.3.1" });
    if (path === "/profile") return reply(200, { account: s.account });
    if (path === "/sessions") {
      return reply(200, {
        sessions: [...this.sessions.entries()]
          .filter(([, x]) => x.account === s.account && !x.ended)
          .map(([v, x]) => ({
            id: Buffer.from(v).toString("base64url").slice(0, 22),
            kind: x === s ? "console" : "login",
            created_at: "2026-11-07T10:00:00Z",
            last_seen_at: "2026-11-07T10:05:00Z",
            current: x === s,
          })),
      });
    }
    const revoke = /^\/sessions\/([^/]+)\/revoke$/.exec(path);
    if (revoke !== null) {
      for (const [v, x] of this.sessions) {
        if (
          Buffer.from(v).toString("base64url").slice(0, 22) === revoke[1] &&
          x.account === s.account
        ) {
          x.ended = true;
          return reply(204);
        }
      }
      return problem(404, "not_found");
    }
    if (path === "/sign-out") {
      s.ended = true;
      return reply(204);
    }
    if (path === "/instances/challenge") {
      const key = Buffer.from(String(body()["key"]), "base64url");
      if (key.length < 64) return problem(400, "invalid-request");
      return reply(201, {
        challenge: Buffer.alloc(32, 5).toString("base64url"),
        expires_at: new Date(Date.now() + 300_000).toISOString(),
        domain: DOMAIN,
        basis: BASIS,
        pep: "access-identity",
        party: PARTY,
        valid_from: "1970-01-01T00:00:01Z",
        valid_until: "1970-01-01T00:00:02Z",
        create: CREATE_ENVELOPE,
      });
    }
    if (path === "/instances") {
      const b = body();
      const cose = Buffer.from(String(b["key"]), "base64url");
      // COSE_Key x (−2) and y (−3) are the last two 32-byte strings
      const x = cose.subarray(cose.length - 67, cose.length - 35);
      const y = cose.subarray(cose.length - 32);
      const raw = Uint8Array.from([4, ...x, ...y]);
      const key = await crypto.subtle.importKey(
        "raw",
        raw,
        { name: "ECDSA", namedCurve: "P-256" },
        true,
        ["verify"],
      );
      const candidate = { ...s, key, kid: "pending" };
      if (!(await this.verify(candidate, String(b["ais"]), "commit"))) {
        return problem(400, "invalid-proof-of-possession");
      }
      s.key = key;
      s.kid = Buffer.from((await k()).thumbprintP256(x, y)).toString("base64url");
      return reply(201, { instance: s.kid });
    }
    if (path.startsWith("/proxy/admin/")) {
      const ais = headers["x-access-ais"];
      if (ais === undefined) return problem(401, "ais-required");
      if (s.kid === undefined) return problem(403, "console-instance-required");
      const mode = r.method() === "GET" ? "check" : "commit";
      if (!(await this.verify(s, ais, mode))) return problem(403, "read-proof-rejected");
      return reply(200, { ok: true });
    }
    if (path === "/proxy/adp/eligibility:check") {
      return reply(200, { eligible: s.kid !== undefined && this.eligible.has(s.account) });
    }
    if (path.startsWith("/proxy/adp/search/")) {
      const b = body();
      const anonymous = b["ais"] === undefined;
      return reply(200, {
        results: anonymous ? [{ id: "public-grant", visibility: "public" }] : [],
        reader: anonymous ? "anonymous" : "instance",
      });
    }
    return problem(404, "not_found");
  }
}
