const P256: Vector<'static> = Vector {
    pkcs8: &P256_PKCS8,
    public: &P256_PUBLIC,
    message: b"sample",
    signature: &P256_SIGNATURE,
};

fn flipped(signature: &[u8]) -> Vec<u8> {
    let mut out = signature.to_vec();
    if let Some(b) = out.first_mut() {
        *b ^= 1;
    }
    out
}

fn ed25519_verifies(public: &[u8], message: &[u8], signature: &[u8]) -> bool {
    sig::ed25519(&AwsLcBackend, public, message, signature).is_ok()
        && sig::ed25519(&PureBackend, public, message, signature).is_ok()
}

fn p256_verifies(public: &[u8], message: &[u8], signature: &[u8]) -> bool {
    sig::p256(&AwsLcBackend, public, message, signature, true).is_ok()
        && sig::p256(&PureBackend, public, message, signature, true).is_ok()
}

fn ed25519(v: &Vector<'_>) -> Result<(), KatError> {
    let signer = SoftSigner::ed25519_from_pkcs8(&Secret::new(v.pkcs8.to_vec()))
        .map_err(|_| KatError::Ed25519)?;
    let PublicKey::Ed25519(public) = signer.public_key() else {
        return Err(KatError::Ed25519);
    };
    let signature = signer.sign(v.message).map_err(|_| KatError::Ed25519)?;
    let known = public.as_slice() == v.public
        && signature == v.signature
        && ed25519_verifies(v.public, v.message, v.signature)
        && !ed25519_verifies(v.public, v.message, &flipped(v.signature));
    known.then_some(()).ok_or(KatError::Ed25519)
}

fn p256(v: &Vector<'_>) -> Result<(), KatError> {
    let signer =
        SoftSigner::p256_from_pkcs8(&Secret::new(v.pkcs8.to_vec())).map_err(|_| KatError::P256)?;
    let PublicKey::P256(public) = signer.public_key() else {
        return Err(KatError::P256);
    };
    let signature = signer.sign(v.message).map_err(|_| KatError::P256)?;
    let known = public == v.public
        && p256_verifies(v.public, v.message, &signature)
        && !p256_verifies(v.public, v.message, &flipped(&signature))
        && p256_verifies(v.public, v.message, v.signature)
        && !p256_verifies(v.public, v.message, &flipped(v.signature));
    known.then_some(()).ok_or(KatError::P256)
}

/// Runs every known-answer test; the signer refuses to start on the first wrong answer.
///
/// # Errors
/// The algorithm whose answer was wrong.
pub fn run() -> Result<(), KatError> {
    ed25519(&ED25519)?;
    p256(&P256)
}

