//! CR-51 m.3: the known-answer tests the signer runs before it serves. Ed25519 signs a fixed
//! message with a fixed seed (RFC 8032 §7.1, test 2) and must give the known signature. ECDSA
//! P-256 is randomized in aws-lc-rs, so a fixed key (RFC 6979 §A.2.5) signs and both backends
//! verify, and the known RFC 6979 signature of "sample" (low-S form, CR-9) verifies. A flipped
//! bit must fail, so a verifier that accepts everything fails the test too.

use suiss_crypto::aws::AwsLcBackend;
use suiss_crypto::cose::PublicKey;
use suiss_crypto::secret::Secret;
use suiss_crypto::sig::{self, PureBackend};
use suiss_crypto::signer::{Signer, SoftSigner};

/// Which algorithm gave a wrong answer.
#[derive(Clone, Copy, Debug, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum KatError {
    /// Ed25519.
    #[error("ed25519 known-answer test failed")]
    Ed25519,
    /// ECDSA P-256.
    #[error("p-256 known-answer test failed")]
    P256,
}

impl KatError {
    /// Stable reason code.
    #[must_use]
    pub const fn code(self) -> &'static str {
        match self {
            Self::Ed25519 => "signer-kat-ed25519",
            Self::P256 => "signer-kat-p256",
        }
    }
}

/// One known answer.
#[derive(Clone, Copy)]
struct Vector<'a> {
    pkcs8: &'a [u8],
    public: &'a [u8],
    message: &'a [u8],
    signature: &'a [u8],
}

