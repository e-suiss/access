use access_kernel::verify::cose::{Algorithm, KeySet, PublicKey};

pub fn keys() -> KeySet {
    let mut ed = [0_u8; 32];
    ed.copy_from_slice(&[
        0xd7, 0x5a, 0x98, 0x01, 0x82, 0xb1, 0x0a, 0xb7, 0xd5, 0x4b, 0xfe, 0xd3, 0xc9, 0x64, 0x07, 0x3a, 0x0e, 0xe1, 0x72,
        0xf3, 0xda, 0xa6, 0x23, 0x25, 0xaf, 0x02, 0x1a, 0x68, 0xf7, 0x07, 0x51, 0x1a,
    ]);
    let mut k = KeySet::default();
    let _ = k.insert([1; 32], PublicKey::Ed25519(ed));
    k.allowed.extend([Algorithm::Ed25519, Algorithm::Esp256, Algorithm::Es256]);
    k
}
